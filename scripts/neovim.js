const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const variants = {};
for (const variant of ['light', 'dark']) {
  const theme = JSON.parse(fs.readFileSync(path.join(root, `sunnyside-${variant}.json`), 'utf8'));
  const c = theme.colors;
  const token = (scope) => theme.tokenColors.find((rule) =>
    (Array.isArray(rule.scope) ? rule.scope : [rule.scope]).includes(scope)).settings.foreground;
  variants[variant] = {
    bg: c['editor.background'], fg: c['editor.foreground'],
    comment: token('comment'), keyword: token('keyword'), string: token('string'),
    constant: token('constant.numeric'), func: theme.semanticTokenColors.function,
    type: theme.semanticTokenColors.type, parameter: theme.semanticTokenColors.parameter,
    property: theme.semanticTokenColors.property, tag: token('entity.name.tag'),
    selection: c['editor.selectionBackground'], line: c['editor.lineHighlightBackground'],
    line_nr: c['editorLineNumber.foreground'], accent: c['editorCursor.foreground'],
    border: c['panel.border'], panel: c['sideBar.background'],
    inactive: c['tab.inactiveForeground'], search: c['editor.findMatchBackground'],
    search_other: c['editor.findMatchHighlightBackground'],
    bracket: c['editorBracketMatch.background'],
    red: c['terminal.ansiRed'], green: c['terminal.ansiGreen'],
    yellow: c['terminal.ansiYellow'], blue: c['terminal.ansiBlue'],
  };
  const names = ['Black', 'Red', 'Green', 'Yellow', 'Blue', 'Magenta', 'Cyan', 'White'];
  variants[variant].terminal = [...names, ...names.map(n => `Bright${n}`)].map(n => c[`terminal.ansi${n}`]);
}
const lua = (value) => Array.isArray(value)
  ? `{ ${value.map(lua).join(', ')} }`
  : typeof value === 'object'
    ? `{\n${Object.entries(value).map(([key, val]) => `  ${key} = ${lua(val)},`).join('\n')}\n}`
    : JSON.stringify(value);
