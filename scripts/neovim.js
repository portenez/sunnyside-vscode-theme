const destination = path.join(root, 'neovim/colors/sunnyside.lua');
if (process.argv.includes('--check')) {
  if (fs.readFileSync(destination, 'utf8') !== content) throw new Error('Neovim theme is stale; run npm run neovim');
} else {
  fs.mkdirSync(path.dirname(destination), { recursive: true });
  fs.writeFileSync(destination, content);
}
