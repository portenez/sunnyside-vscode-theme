const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const ansi = ['Black', 'Red', 'Green', 'Yellow', 'Blue', 'Magenta', 'Cyan', 'White'];
const roles = [...ansi, ...ansi.map((name) => `Bright${name}`)];

for (const variant of ['light', 'dark']) {
  const { colors } = JSON.parse(fs.readFileSync(path.join(root, `sunnyside-${variant}.json`), 'utf8'));
  const settings = {
    background: colors['terminal.background'],
    foreground: colors['terminal.foreground'],
    'cursor-color': colors['terminalCursor.foreground'],
    'cursor-text': colors['terminal.background'],
    'selection-background': colors['editor.selectionBackground'],
    'selection-foreground': colors['terminal.foreground'],
  };
  const name = `Sunnyside ${variant === 'light' ? 'Light' : 'Dark'}`;
  const content = [
    `# ${name} — MIT License`,
    '# Generated by npm run ghostty; edit the source VS Code theme instead.',
    ...Object.entries(settings).map(([key, value]) => `${key} = ${value}`),
    '',
    ...roles.map((role, index) => `palette = ${index}=${colors[`terminal.ansi${role}`]}`),
    '',
  ].join('\n');
  const destination = path.join(root, 'ghostty', name);
  if (process.argv.includes('--check')) {
    if (fs.readFileSync(destination, 'utf8') !== content) {
      throw new Error(`${name} is stale; run npm run ghostty`);
    }
  } else {
    fs.mkdirSync(path.dirname(destination), { recursive: true });
    fs.writeFileSync(destination, content);
  }
}
